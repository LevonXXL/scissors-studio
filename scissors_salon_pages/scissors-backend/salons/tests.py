from django.urls import reverse
from rest_framework.test import APITestCase

from .models import Salon


class SalonSlugTests(APITestCase):
    def _salon(self, name, **kw):
        return Salon.objects.create(name=name, address='а', latitude='0', longitude='0', **kw)

    def test_slug_autogenerated_from_name(self):
        self.assertEqual(self._salon('Зеленоград').slug, 'zelenograd')

    def test_manual_slug_is_preserved(self):
        self.assertEqual(self._salon('Москва, Красные ворота', slug='moscow').slug, 'moscow')

    def test_slug_collision_gets_suffix(self):
        a = self._salon('Тест')
        b = self._salon('Тест')
        self.assertNotEqual(a.slug, b.slug)

    def test_detail_by_slug_exposes_booking_and_seo_fields(self):
        self._salon('Москва', slug='moscow', yclients_company_id='128411')
        response = self.client.get(reverse('salon-detail', args=['moscow']))
        self.assertEqual(response.status_code, 200)
        for field in ('slug', 'name', 'address', 'coordinates', 'photos', 'description', 'yclients_company_id'):
            self.assertIn(field, response.data)

    def test_inactive_salon_is_404(self):
        self._salon('Скрытый', slug='hidden', is_active=False)
        self.assertEqual(self.client.get(reverse('salon-detail', args=['hidden'])).status_code, 404)


class SalonPhotoThumbnailTests(APITestCase):
    """Проверка на реальном файле: превью действительно создаётся нужного размера,
    а битый файл не роняет API."""

    def setUp(self):
        import io
        from django.core.files.base import ContentFile
        from filer.models import Image as FilerImage
        from PIL import Image as PILImage
        from .models import SalonPhoto

        self.salon = Salon.objects.create(name='Москва', slug='moscow', address='а', latitude='0', longitude='0')
        buf = io.BytesIO()
        PILImage.new('RGB', (2400, 1800), (200, 30, 30)).save(buf, 'PNG')
        self.filer_image = FilerImage.objects.create(
            file=ContentFile(buf.getvalue(), name='big.png'), original_filename='big.png',
        )
        SalonPhoto.objects.create(salon=self.salon, image=self.filer_image, position=0)

    def test_thumbnail_and_large_versions_generated(self):
        from PIL import Image as PILImage
        from django.conf import settings
        import os

        photo = self.client.get(reverse('salon-detail', args=['moscow'])).data['photos'][0]
        self.assertNotEqual(photo['thumbnail'], photo['image'])
        self.assertEqual((photo['thumbnail_width'], photo['thumbnail_height']), (600, 400))

        def local(url):
            return os.path.join(settings.MEDIA_ROOT, url.split(settings.MEDIA_URL, 1)[1])

        with PILImage.open(local(photo['thumbnail'])) as im:
            self.assertEqual(im.size, (600, 400))        # кадрирование под сетку
        with PILImage.open(local(photo['image'])) as im:
            self.assertEqual(im.size, (1600, 1200))       # ужато до 1600 с сохранением пропорций

    def test_missing_file_falls_back_instead_of_500(self):
        self.filer_image.file.storage.delete(self.filer_image.file.name)
        response = self.client.get(reverse('salon-detail', args=['moscow']))
        self.assertEqual(response.status_code, 200)
        self.assertTrue(response.data['photos'][0]['image'])
